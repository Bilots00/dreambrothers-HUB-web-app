// Scheduler in-process (il server Railway è always-on): job giornalieri a orario
// fisso italiano, indipendenti dai bottoni della UI e dal browser aperto.
//   08:45 → refresh Watchlist (canali competitor)
//   09:00 → refresh Research Hub (fonti + punteggi AI + autopilot)
// L'orario si ricalcola ogni giorno dal fuso Europe/Rome (DST-safe).
const OWNER_USER_ID = 1;
const TIMEZONE = "Europe/Rome";

function secondsIntoRomeDay(): number {
  const parts = new Intl.DateTimeFormat("en-GB", {
    timeZone: TIMEZONE, hour: "2-digit", minute: "2-digit", second: "2-digit", hour12: false,
  }).formatToParts(new Date());
  const get = (type: string) => Number(parts.find((p) => p.type === type)?.value ?? 0);
  return (get("hour") % 24) * 3600 + get("minute") * 60 + get("second");
}

function msUntilNext(hour: number, minute: number): number {
  const target = hour * 3600 + minute * 60;
  let delta = target - secondsIntoRomeDay();
  if (delta <= 30) delta += 86_400; // già passato (o troppo vicino): domani
  return delta * 1000;
}

function scheduleDaily(hour: number, minute: number, name: string, fn: () => Promise<void>) {
  const arm = () => {
    const delay = msUntilNext(hour, minute);
    console.log(`[Scheduler] "${name}" tra ${Math.round(delay / 60000)} min (ogni giorno ${String(hour).padStart(2, "0")}:${String(minute).padStart(2, "0")} ${TIMEZONE})`);
    const timer = setTimeout(async () => {
      try {
        await fn();
      } catch (err) {
        console.warn(`[Scheduler] "${name}" fallito:`, err);
      }
      arm(); // riprogramma il giorno dopo
    }, delay);
    timer.unref?.(); // non tenere vivo il processo solo per il timer
  };
  arm();
}

// Fallback quando il server non ha un motore AI sincrono: il MOTORE PRIMARIO è
// l'agente VPS (abbonamento Claude). Se l'agente è online ma con codice pre-v5
// (senza research_loop), gli si chiede il lavoro via chat bridge.
const AGENT_ENRICH_TASK = `[SEO → ENRICH] Task automatico giornaliero del Research Hub.
Esegui in bash (il secret è già nel tuo ambiente, altrimenti: source ~/.social-agent.env):
1) curl -s -H "x-care-secret: $CARE_WEBHOOK_SECRET" "$SOCIAL_BASE_URL/api/seo/research/pending-enrich"
2) Per ogni item valuta CONTRO il brand_context ricevuto: targetScore 0-10, interestScore 0-10, brief (1-2 frasi it), angle (chiave di lettura brand), commentAnalysis+engagement per i reddit se leggibili dall'url (.rss).
3) POST il JSON {"items":[...]} a "$SOCIAL_BASE_URL/api/seo/research/enrichment" con lo stesso header.
Rispondi in chat solo con: quanti item hai analizzato.`;

export function registerDailySchedules() {
  if (!process.env.DATABASE_URL) {
    console.log("[Scheduler] DATABASE_URL assente — scheduler spento (dev locale)");
    return;
  }

  scheduleDaily(8, 45, "watchlist-refresh", async () => {
    const r = await refreshAllWatchlistChannels(OWNER_USER_ID);
    console.log(`[Scheduler] watchlist: ${r.refreshed} canali aggiornati, ${r.errors.length} errori`);
  });

  scheduleDaily(9, 0, "research-refresh", async () => {
    const r = await refreshResearch(OWNER_USER_ID);
    console.log(`[Scheduler] research 09:00: fetched=${r.fetched} stored=${r.stored} enriched=${r.enriched} autopilot=${r.autoGenerated} errori=${r.errors.length}`);
    // niente motore sincrono e niente research_loop attivo? chiedi all'agente via chat
    if (r.enriched === 0 && r.errors.some((e) => /Nessun motore AI/i.test(e))) {
      const s = await getAllUserSettings(OWNER_USER_ID);
      const lastSeen = Number(s.social_local_agent_last_seen ?? 0);
      if (lastSeen > 0 && Date.now() - lastSeen < 300_000) {
        await insertSocialChatMessage({
          userId: OWNER_USER_ID, role: "user", text: AGENT_ENRICH_TASK, status: "new", source: "web",
        }).catch((err) => console.warn("[Scheduler] handoff chat fallito:", err));
        console.log("[Scheduler] nessun motore sul server: enrichment delegato all'agente via chat bridge");
      }
    }
  });

  scheduleDaily(9, 15, "market-monitor", async () => {
    const r = await runAllStoresCycle(OWNER_USER_ID);
    console.log(`[Scheduler] market 09:15: stores=${r.stores} changes=${r.changes} errori=${r.errors.length}`);
    try { await enrichPendingMarketChanges(OWNER_USER_ID); } catch (e) { console.warn("[Scheduler] market enrich fallito:", e); }
  });

  // Lunedì 09:30 — digest Pinterest in nicchia: l'agente Claude (VPS) aggiorna la
  // nota Brain pinterest-keywords-digest.md per SMM + Creative Director (Task 5
  // della skill seo-research). Il trigger passa dal bridge chat esistente.
  scheduleDaily(9, 30, "pinterest-digest", async () => {
    const dow = new Intl.DateTimeFormat("en-GB", { timeZone: TIMEZONE, weekday: "short" }).format(new Date());
    if (dow !== "Mon") return;
    await insertSocialChatMessage({
      userId: OWNER_USER_ID, role: "user", source: "web", status: "new",
      text: `[SEO → PINTEREST DIGEST] Task settimanale: esegui il Task 5 della skill seo-research (in ~/.claude/skills/seo-research o claude-bot-workspace/skills). In sintesi: 1) GET $SOCIAL_BASE_URL/api/seo/research/items?source=pinterest&hours=168&min_target=6&limit=30 (header x-care-secret: $CARE_WEBHOOK_SECRET, env in ~/.social-agent.env); 2) leggi la pagina pubblica https://business.pinterest.com/it/pinterest-predicts/ per i temi annuali in nicchia; 3) aggiorna la nota Brain areas/marketing/social-media/pinterest-keywords-digest.md (repo ~/projects/dreambrothers-brain, poi git add/commit/push) con la tabella keyword in nicchia (indice /100, crescita, perché è nostra) e i temi Predicts; 4) rispondi in chat con le 3 keyword top della settimana. NON scrapare trends.pinterest.com/shopping o /search (richiedono login).`,
    }).catch((err) => console.warn("[Scheduler] pinterest digest handoff fallito:", err));
    console.log("[Scheduler] pinterest-digest: task settimanale inviato all'agente");
  });

  scheduleDaily(9, 45, "etsy-watchlist", async () => {
    const r = await runAllEtsyShops(OWNER_USER_ID);
    console.log(`[Scheduler] etsy 09:45: shops=${r.shops} listings=${r.listings} errori=${r.errors.length}`);
  });

  // Ads Inspiration: refresh giornaliero delle ads dei brand in watchlist
  scheduleDaily(10, 0, "ads-library-refresh", async () => {
    const r = await refreshAllBrands(OWNER_USER_ID);
    console.log(`[Scheduler] ads-library 10:00: brands=${r.brands} ingested=${r.ingested} errori=${r.errors.length}`);
  });

  // Prodotti in evidenza del giorno: l'agente fuso incrocia i candidati raccolti
  scheduleDaily(10, 15, "daily-picks", async () => {
    const day = new Intl.DateTimeFormat("en-CA", { timeZone: TIMEZONE, year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());
    const r = await generateDailyPicks(OWNER_USER_ID, day);
    console.log(`[Scheduler] daily-picks 10:15: ${r.count} prodotti in evidenza (LLM=${r.usedLLM})`);
  });

  // Mission Control: ciclo del team agenti Paid Advertising ogni 30 minuti
  // (Vega verifica ads live, Sirius scrive update performance, Nova raccomanda).
  // Il service esce subito se non ci sono campagne ACTIVE gestite dagli agenti.
  const AGENTS_CYCLE_MS = 30 * 60 * 1000;
  const agentsTimer = setInterval(async () => {
    try {
      const r = await runAgentsCycle(OWNER_USER_ID);
      if (r.campaignsChecked > 0) {
        console.log(`[Scheduler] meta-agents-cycle: campagne=${r.campaignsChecked} update=${r.updates} alert=${r.alertsRaised}`);
      }
    } catch (err) {
      console.warn("[Scheduler] meta-agents-cycle fallito:", err);
    }
  }, AGENTS_CYCLE_MS);
  agentsTimer.unref?.();
  console.log("[Scheduler] \"meta-agents-cycle\" attivo ogni 30 min (solo campagne gestite dagli agenti)");

  // Chargeback Shopify ogni 20 minuti. E' la rete di sicurezza del webhook
  // disputes/*: se il webhook non e' registrato, o una consegna si perde, la
  // contestazione salta fuori comunque entro 20 minuti invece che per caso
  // giorni dopo (il caso #1261). Senza token Shopify non c'e' niente da
  // chiedere, e il job si spegne da solo.
  if (process.env.SHOPIFY_SHOP && process.env.SHOPIFY_ADMIN_TOKEN) {
    const CHARGEBACK_POLL_MS = 20 * 60 * 1000;
    const eseguiSync = async () => {
      try {
        const r = await sincronizzaChargebacks();
        if (r.nuovi > 0 || r.aggiornati > 0 || r.errori.length > 0) {
          console.log(`[Scheduler] chargeback-sync: trovati=${r.trovati} nuovi=${r.nuovi} aggiornati=${r.aggiornati} errori=${r.errori.length}`);
        }
      } catch (err) {
        console.warn("[Scheduler] chargeback-sync fallito:", err);
      }
    };
    // Un giro al boot: se una contestazione e' arrivata mentre il server era
    // giu', aspettare i primi 20 minuti sarebbe tempo regalato alla scadenza.
    setTimeout(eseguiSync, 30_000).unref?.();
    const chargebackTimer = setInterval(eseguiSync, CHARGEBACK_POLL_MS);
    chargebackTimer.unref?.();
    console.log("[Scheduler] \"chargeback-sync\" attivo ogni 20 min");
  } else {
    console.log("[Scheduler] chargeback-sync spento — mancano SHOPIFY_SHOP / SHOPIFY_ADMIN_TOKEN");
  }

  // Cane da guardia dei canali clienti, ogni ora. Non trasporta messaggi: conta
  // i silenzi. Gira qui e non in n8n proprio perche' deve poter dire "n8n e'
  // morto" — e il 29 giugno n8n e' morto in silenzio per due mesi.
  const WATCHDOG_MS = 60 * 60 * 1000;
  const eseguiWatchdog = async () => {
    try {
      const r = await giroWatchdog();
      if (r.nuoviAllarmi.length || r.riaccesi.length || r.rientrati.length) {
        console.log(`[Scheduler] care-watchdog: allarmi=${r.nuoviAllarmi.join(",") || "-"} riaccesi=${r.riaccesi.join(",") || "-"} rientrati=${r.rientrati.join(",") || "-"}`);
      }
    } catch (err) {
      console.warn("[Scheduler] care-watchdog fallito:", err);
    }
  };
  setTimeout(eseguiWatchdog, 90_000).unref?.();
  const watchdogTimer = setInterval(eseguiWatchdog, WATCHDOG_MS);
  watchdogTimer.unref?.();
  console.log("[Scheduler] \"care-watchdog\" attivo ogni ora (silenzio dei canali clienti)");

  // Wall art in automatico: le pubblicazioni approvate che aspettano i file di
  // stampa dal VPS. Il poller le riprende appena i PNG compaiono nella repo
  // dell'agente; senza token GitHub non c'e' niente da riprendere.
  if (process.env.PRODUCT_ARTIST_GITHUB_TOKEN || process.env.SEO_AGENT_GITHUB_TOKEN || process.env.GITHUB_TOKEN) {
    const WALLART_POLL_MS = 3 * 60 * 1000;
    const wallartTimer = setInterval(async () => {
      try {
        await riprendiWallartAuto();
      } catch (err) {
        console.warn("[Scheduler] wallart-auto fallito:", err);
      }
    }, WALLART_POLL_MS);
    wallartTimer.unref?.();
    console.log("[Scheduler] \"wallart-auto\" attivo ogni 3 min (quadri approvati in modalita' automatica)");
  }
}
